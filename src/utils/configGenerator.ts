export function generateUserCustomIni(config: GfxConfigState): string {
  // Map FPS to UE4 PUBGDeviceFPSPolicy
  // 3 = 30 FPS, 4 = 40 FPS, 5 = 60 FPS, 6 = 90 FPS, 7 = 120 FPS
  const fpsPolicyMap: Record<number, number> = {
    30: 3,
    40: 4,
    60: 5,
    90: 6,
    120: 7,
  };

  // Map Graphics Quality
  // 0 = Smooth, 1 = Balanced, 2 = HD, 3 = HDR, 4 = Ultra HD
  const qualityMap: Record<string, number> = {
    potato: 0,
    smooth: 1,
    balanced: 2,
    hd: 3,
    hdr: 4,
    ultra_hd: 5,
  };

  // Color Style
  // 1 = Classic, 2 = Colorful, 3 = Realistic, 4 = Soft, 5 = Movie
  const styleMap: Record<string, number> = {
    classic: 1,
    colorful: 2,
    realistic: 3,
    soft: 4,
    movie: 5,
  };

  // Screen scale percentage
  const resolutionMap: Record<string, { pct: number; scale: string }> = {
    '540p': { pct: 70, scale: '0.8' },
    '720p': { pct: 85, scale: '1.0' },
    '1080p': { pct: 100, scale: '1.25' },
    '2k': { pct: 125, scale: '1.5' },
    native: { pct: 100, scale: '1.0' },
  };

  const antiAliasingVal = config.antiAliasing === '4x' ? 2 : config.antiAliasing === '2x' ? 1 : 0;
  const shadowVal = config.shadows ? 1 : 0;
  const lightEffectsVal = config.lightEffects ? 1 : 0;
  const audioVal = config.audioQuality === 'ultra' ? 2 : config.audioQuality === 'high' ? 1 : 0;

  const res = resolutionMap[config.resolution] || resolutionMap['1080p'];
  const fpsCode = fpsPolicyMap[config.fps] || 5;
  const qualityCode = qualityMap[config.graphics] ?? 1;
  const styleCode = styleMap[config.style] || 2;

  const timestamp = new Date().toISOString();

  return `[UserCustom DeviceProfile]
; Generated by AK GFX Tool - Fair Play Compliant Engine
; Timestamp: ${timestamp}
; Target FPS: ${config.fps} FPS | Graphics: ${config.graphics.toUpperCase()}
+CVars=r.PUBGDeviceFPSPolicy=${fpsCode}
+CVars=r.PUBGQualityLevel=${qualityCode}
+CVars=r.UserQualitySetting=${qualityCode}
+CVars=r.ScreenPercentage=${res.pct}
+CVars=r.MobileContentScaleFactor=${res.scale}
+CVars=r.PUBGColorStyle=${styleCode}
+CVars=r.ShadowQuality=${shadowVal}
+CVars=r.DefaultFeature.AntiAliasing=${antiAliasingVal}
+CVars=r.PUBGMSAASetting=${antiAliasingVal}
+CVars=r.PUBGLightSetting=${lightEffectsVal}
+CVars=r.AudioQuality=${audioVal}
+CVars=r.PUBGRenderAPI=${config.renderingApi === 'vulkan' ? 'Vulkan' : 'Default'}
+CVars=r.GPUOptimization=${config.gpuOptimization ? 1 : 0}
+CVars=r.MaterialQualityLevel=${qualityCode >= 3 ? 1 : 0}
`.trim();
}

export function getConfigFilePath(packageName: string): string {
  return `Android/data/${packageName}/files/UE4Game/ShadowTrackerExtra/ShadowTrackerExtra/Saved/Config/Android/UserCustom.ini`;
}

export function parseUserCustomIni(iniText: string): Partial<GfxConfigState> {
  const parsed: Partial<GfxConfigState> = {};

  const lines = iniText.split('\n');
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed.startsWith('+CVars=')) continue;

    const [key, val] = trimmed.replace('+CVars=', '').split('=');
    if (!key || val === undefined) continue;

    switch (key) {
      case 'r.PUBGDeviceFPSPolicy': {
        const num = parseInt(val, 10);
        if (num === 7) parsed.fps = 120;
        else if (num === 6) parsed.fps = 90;
        else if (num === 5) parsed.fps = 60;
        else if (num === 4) parsed.fps = 40;
        else if (num === 3) parsed.fps = 30;
        break;
      }
      case 'r.PUBGQualityLevel': {
        const num = parseInt(val, 10);
        if (num === 0) parsed.graphics = 'potato';
        else if (num === 1) parsed.graphics = 'smooth';
        else if (num === 2) parsed.graphics = 'balanced';
        else if (num === 3) parsed.graphics = 'hd';
        else if (num === 4) parsed.graphics = 'hdr';
        else if (num === 5) parsed.graphics = 'ultra_hd';
        break;
      }
      case 'r.PUBGColorStyle': {
        const num = parseInt(val, 10);
        if (num === 1) parsed.style = 'classic';
        else if (num === 2) parsed.style = 'colorful';
        else if (num === 3) parsed.style = 'realistic';
        else if (num === 4) parsed.style = 'soft';
        else if (num === 5) parsed.style = 'movie';
        break;
      }
      case 'r.ShadowQuality': {
        parsed.shadows = val === '1' || val === '2';
        break;
      }
      case 'r.AudioQuality': {
        const num = parseInt(val, 10);
        if (num >= 2) parsed.audioQuality = 'ultra';
        else if (num === 1) parsed.audioQuality = 'high';
        else parsed.audioQuality = 'low';
        break;
      }
      case 'r.PUBGRenderAPI': {
        if (/vulkan/i.test(val)) parsed.renderingApi = 'vulkan';
        else if (/opengl/i.test(val)) parsed.renderingApi = 'opengl';
        else parsed.renderingApi = 'default';
        break;
      }
      case 'r.ScreenPercentage': {
        const pct = parseInt(val, 10);
        if (pct <= 70) parsed.resolution = '540p';
        else if (pct <= 85) parsed.resolution = '720p';
        else if (pct <= 100) parsed.resolution = '1080p';
        else parsed.resolution = '2k';
        break;
      }
      case 'r.GPUOptimization': {
        parsed.gpuOptimization = val === '1';
        break;
      }
    }
  }

  return parsed;
}

export interface CVarAnalysis {
  cvar: string;
  value: string;
  meaning: string;
  impact: string;
  badgeColor: string;
}

export function analyzeCvars(iniText: string): CVarAnalysis[] {
  const result: CVarAnalysis[] = [];
  const lines = iniText.split('\n');

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed.startsWith('+CVars=')) continue;

    const [key, val] = trimmed.replace('+CVars=', '').split('=');
    if (!key || val === undefined) continue;

    if (key === 'r.PUBGDeviceFPSPolicy') {
      const fps = val === '7' ? '120 FPS' : val === '6' ? '90 FPS' : val === '5' ? '60 FPS' : '30/40 FPS';
      result.push({
        cvar: key,
        value: val,
        meaning: `Unlocks ${fps} Framerate`,
        impact: 'Removes 60 FPS cap on supported 90Hz/120Hz displays',
        badgeColor: '#00ff80',
      });
    } else if (key === 'r.PUBGQualityLevel') {
      const g = val === '0' ? 'Potato' : val === '1' ? 'Smooth' : val === '2' ? 'Balanced' : 'HD/HDR';
      result.push({
        cvar: key,
        value: val,
        meaning: `${g} Graphics Quality`,
        impact: 'Low texture memory usage, eliminates frame drop spikes',
        badgeColor: '#00e5ff',
      });
    } else if (key === 'r.PUBGColorStyle') {
      const s = val === '2' ? 'Colorful' : val === '1' ? 'Classic' : val === '3' ? 'Realistic' : 'Soft';
      result.push({
        cvar: key,
        value: val,
        meaning: `${s} Visual Style`,
        impact: 'Sharp saturated colors for rapid enemy spotting in grass & shadows',
        badgeColor: '#f472b6',
      });
    } else if (key === 'r.AudioQuality') {
      const a = val === '2' ? 'Ultra SFX 3D Audio' : val === '1' ? 'High SFX' : 'Low SFX';
      result.push({
        cvar: key,
        value: val,
        meaning: a,
        impact: 'Unlocks 360-degree positional sound for enemy footstep & gunshot tracking',
        badgeColor: '#a855f7',
      });
    } else if (key === 'r.PUBGRenderAPI') {
      result.push({
        cvar: key,
        value: val,
        meaning: `${val} Graphics Pipeline`,
        impact: 'Lower CPU overhead, cooler phone temperatures during long matches',
        badgeColor: '#38bdf8',
      });
    } else if (key === 'r.ShadowQuality') {
      result.push({
        cvar: key,
        value: val,
        meaning: val === '1' ? 'Dynamic Shadows Enabled' : 'Shadows Disabled',
        impact: val === '1' ? 'Realistic player & tree shadows' : '+15% FPS boost in smoke',
        badgeColor: '#fbbf24',
      });
    }
  }

  return result;
}
